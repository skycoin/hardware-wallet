// oledDrawBitmap draws a 128x64 1bpp bitmap to the display buffer
func oledDrawBitmap(data *[1024]byte) {
	for y := 0; y < 64; y++ {
		for x := 0; x < 128; x++ {
			byteIdx := y*16 + x/8
			bitIdx := 7 - (x % 8) // MSB first
			if data[byteIdx]&(1<<bitIdx) != 0 {
				oledSetPixel(x, y, true)
			}
		}
	}
}
